/**
 * docs/state-machines.md, generated from the transition tables in the code (docs/decisions/0008) so the document
 * cannot drift: `bun run docs:machines` writes it and test/stateMachines.test.ts fails when it is out of date.
 */
import * as Machine from "@file-transfer/machine"
import { relaySessionMachine } from "@file-transfer/service-relay"
import { roomMachine } from "@file-transfer/service-room"

export const stateMachinesFile = "docs/state-machines.md"

interface Section {
  readonly name: string
  readonly source: string
  readonly diagram: string
  readonly table: string
}

const section = <State extends string, Command extends string, Context>(source: string, machine: Machine.Machine<State, Command, Context>): Section => ({
  name: machine.name,
  source,
  diagram: Machine.toMermaid(machine),
  table: Machine.toTable(machine),
})

const sections: readonly Section[] = [section("services/room", roomMachine), section("services/relay", relaySessionMachine)]

export const stateMachineDocument = (): string =>
  [
    "# State machines",
    "",
    "Generated by `bun run docs:machines` from the transition tables in the code (docs/decisions/0008). Do not edit it by hand: a test fails when it is out of date.",
    "",
    "Each machine has a diagram and a table. The table is normative: it has a cell for every state and command, so an input the diagram does not show appears there as `rejected`. A rejected command fails with a typed error and leaves the state as it was. `[*]` is the boundary, before the resource exists or after it is gone, so its row says what happens to a command on a resource that does not exist. The `follows-machine` guarantee of each service's conformance suite checks every cell, illegal ones included.",
    "",
    ...sections.flatMap((entry) => [`## ${entry.name} (\`${entry.source}\`)`, "", "```mermaid", entry.diagram, "```", "", entry.table, ""]),
    "## Not yet tables",
    "",
    "The browser's sender, recipient and connection life cycles are still a status field plus flags (docs/invariants.md, gap G2), so they have no table here yet.",
    "",
  ].join("\n")
