/**
 * Writes the configuration for the single-file server node (`dist/node.capnp`): workerd.capnp with the web app's
 * files embedded as data modules instead of read from a `public` directory, so `workerd compile` can turn it into one
 * executable that needs nothing beside it but a writable storage directory (docs/decisions/0021).
 *
 *   bun run build && bun scripts/nodeConfig.ts && workerd compile dist/node.capnp > dist/file-transfer-node
 *
 * The files worker it generates answers like workerd's disk service does for the assets worker: the file's bytes
 * for a path that exists, 404 otherwise.
 */
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs"
import nodePath from "node:path"

const packageDirectory = nodePath.join(import.meta.dirname, "..")
const publicDirectory = nodePath.join(packageDirectory, "public")
const distDirectory = nodePath.join(packageDirectory, "dist")

const listFiles = (directory: string): string[] =>
  readdirSync(directory).flatMap((entry) => {
    const path = nodePath.join(directory, entry)

    return statSync(path).isDirectory() ? listFiles(path) : [path]
  })

const files = listFiles(publicDirectory)
  .map((path) => nodePath.relative(publicDirectory, path).split(nodePath.sep).join("/"))
  .toSorted()

if (!files.includes("index.html")) {
  throw new Error("public/index.html is missing: run `bun run build` first")
}

// Module names are the file paths under a prefix, so they cannot collide with the worker module itself.
const moduleName = (file: string) => `public/${file}`

const filesWorker = [
  "// Generated by scripts/nodeConfig.ts: the web app's files, embedded as data modules.",
  ...files.map((file, index) => `import file${index} from ${JSON.stringify(moduleName(file))}`),
  "const files = new Map([",
  ...files.map((file, index) => `  [${JSON.stringify(`/${file}`)}, file${index}],`),
  "])",
  "export default {",
  "  fetch(request) {",
  "    const body = files.get(new URL(request.url).pathname)",
  "    return body === undefined ? new Response(null, { status: 404 }) : new Response(body)",
  "  },",
  "}",
  "",
].join("\n")

writeFileSync(nodePath.join(distDirectory, "files-worker.js"), filesWorker)

const diskFiles = '(name = "files", disk = (path = "public", writable = false)),'
const source = readFileSync(nodePath.join(packageDirectory, "workerd.capnp"), "utf-8")

if (!source.includes(diskFiles)) {
  throw new Error("workerd.capnp no longer declares the files disk service this script replaces")
}

// Paths in `embed` are relative to the configuration file, which lives in dist/.
const configuration = `${source.replace(diskFiles, '(name = "files", worker = .filesWorker),').replaceAll('embed "dist/', 'embed "')}
const filesWorker :Workerd.Worker = (
  modules = [
    (name = "files-worker.js", esModule = embed "files-worker.js"),
${files.map((file) => `    (name = ${JSON.stringify(moduleName(file))}, data = embed ${JSON.stringify(`../public/${file}`)}),`).join("\n")}
  ],
  compatibilityDate = "2026-10-01",
);
`

writeFileSync(nodePath.join(distDirectory, "node.capnp"), `# Generated by scripts/nodeConfig.ts from workerd.capnp; do not edit.\n${configuration}`)

console.log(`wrote dist/node.capnp with ${files.length} embedded files`)
