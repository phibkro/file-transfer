/**
 * Writes the self-contained bundle the Deploy to Cloudflare button deploys (docs/decisions/0019-open-source-first.md):
 * the built Worker, apps/web's build and a wrangler.jsonc that points at them, with nothing to install or build. The
 * button does not fully support monorepos (https://developers.cloudflare.com/workers/platform/deploy-buttons/), so CI
 * publishes this directory to the `deploy` branch and the button points there.
 *
 *   bun run build:all && bun scripts/deployBundle.ts <output directory>
 */
import { cpSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs"
import nodePath from "node:path"
import * as v from "valibot"

const output = process.argv[2]

if (output === undefined) {
  throw new Error("usage: bun scripts/deployBundle.ts <output directory>")
}

const packageDirectory = new URL("..", import.meta.url).pathname
const repositoryDirectory = nodePath.join(packageDirectory, "../..")
const sourceUrl = "https://github.com/phibkro/file-transfer"

// The one declaration of the Worker; the bundle changes only where its files live, and keeps every other field.
const Wrangler = v.looseObject({ main: v.string(), assets: v.looseObject({ directory: v.string() }) })
const wranglerModule: unknown = await import(nodePath.join(packageDirectory, "wrangler.jsonc"))
const wrangler = v.parse(v.object({ default: Wrangler }), wranglerModule).default
const bundleConfiguration = { ...wrangler, main: "worker.js", assets: { ...wrangler.assets, directory: "public" } }

rmSync(output, { recursive: true, force: true })

mkdirSync(output, { recursive: true })

cpSync(nodePath.join(packageDirectory, "dist/worker.js"), nodePath.join(output, "worker.js"))

cpSync(nodePath.join(repositoryDirectory, "apps/web/dist"), nodePath.join(output, "public"), { recursive: true })

cpSync(nodePath.join(repositoryDirectory, "LICENSE"), nodePath.join(output, "LICENSE"))

writeFileSync(
  nodePath.join(output, "wrangler.jsonc"),
  `// Generated from platforms/cloudflare/wrangler.jsonc in ${sourceUrl}; change settings in "vars" or the dashboard.\n${JSON.stringify(bundleConfiguration, undefined, 2)}\n`,
)

// The one secret the button asks for (optional); the address salt is generated on first use. See "Run your own".
writeFileSync(
  nodePath.join(output, ".dev.vars.example"),
  ["# Opens /admin and /api/admin/* for you, the operator. Leave empty to keep them closed.", "ADMIN_TOKEN=", ""].join("\n"),
)

writeFileSync(
  nodePath.join(output, "package.json"),
  `${JSON.stringify(
    {
      name: "file-transfer",
      private: true,
      license: "AGPL-3.0-only",
      description: "End-to-end encrypted file transfer, prebuilt for Deploy to Cloudflare",
      repository: sourceUrl,
      cloudflare: {
        bindings: {
          ROOMS: { description: "One Durable Object per transfer room; it relays ciphertext and keeps no files." },
          ADMISSION: { description: "Counts rooms per hashed client address per hour, for the rate limit." },
          COUNTER_STORE: { description: "Opt-in aggregate counters; empty unless COUNTERS is on." },
          RELAY_BUDGET: { description: "Bytes relayed today, against LIMIT_RELAYED_BYTES_PER_DAY; resets at 00:00 UTC." },
          ADMIN_TOKEN: { description: "Optional. Opens the operator page at /admin. Leave empty to keep it closed." },
          ADDRESS_SALT_STORE: { description: "Keeps the random salt for address hashes, generated on first use." },
        },
      },
    },
    undefined,
    2,
  )}\n`,
)

const commit = process.env.GITHUB_SHA ?? "local"

writeFileSync(
  nodePath.join(output, "README.md"),
  `# file-transfer, ready to deploy

End-to-end encrypted file transfer from your browser: files are encrypted on the sender's device and decrypted on the
recipient's; this server relays ciphertext and keeps no files.

This branch is generated by CI from [${sourceUrl}](${sourceUrl}) (commit ${commit}). It holds the built Worker, the
built web app and a \`wrangler.jsonc\`, so it deploys without a build step:

[![Deploy to Cloudflare](https://deploy.workers.cloudflare.com/button)](https://deploy.workers.cloudflare.com/?url=${sourceUrl}/tree/deploy)

Change limits in \`wrangler.jsonc\` (\`vars\`) or in the Cloudflare dashboard. The source code, documentation and issue
tracker are in the main repository. Free software under the AGPL-3.0: if you change the code for others to use, offer
them your source.
`,
)

console.log(
  `wrote the deploy bundle to ${output} (${JSON.stringify(readFileSync(nodePath.join(output, "wrangler.jsonc"), "utf-8").length)} bytes of configuration)`,
)
