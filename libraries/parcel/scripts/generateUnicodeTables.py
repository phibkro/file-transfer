"""
Generates libraries/parcel/src/unicode.ts: the Unicode 15.1 data the name profile needs (docs/parcel.md,
"Name profile"), fixed so every implementation compares names the same way whatever Unicode version its
runtime carries. Requires Python whose unicodedata is 15.1 (Python 3.13).

Run: python3 -I libraries/parcel/scripts/generateUnicodeTables.py > libraries/parcel/src/unicode.ts
"""

import sys
import unicodedata

if unicodedata.unidata_version != "15.1.0":
    raise SystemExit(f"needs Unicode 15.1 data, this Python has {unicodedata.unidata_version}")

forbidden_categories = {"Cc", "Cf", "Zl", "Zp", "Cs", "Cn"}
ranges = []
for code_point in range(0x110000):
    if unicodedata.category(chr(code_point)) in forbidden_categories:
        if ranges and ranges[-1][1] == code_point - 1:
            ranges[-1][1] = code_point
        else:
            ranges.append([code_point, code_point])

folds = []
for code_point in range(0x110000):
    if 0xD800 <= code_point <= 0xDFFF:
        continue
    folded = chr(code_point).casefold()
    if folded != chr(code_point):
        folds.append([code_point, *[ord(character) for character in folded]])

out = sys.stdout
out.write("// oxlint-effect-plugin ignore-file:\n")
out.write(
    "// reason: the parcel library is MIT and deliberately free of Effect so other clients can adopt it; "
    "Web Crypto is its one capability and callers wrap it (docs/decisions/0009)\n"
)
out.write("/**\n * Generated by scripts/generateUnicodeTables.py from Unicode 15.1 (Python unicodedata). Do not edit.\n")
out.write(" * Name profile data (docs/parcel.md): forbidden code point ranges (General Category Cc, Cf, Zl, Zp, Cs, Cn) and full\n")
out.write(" * default case folding (CaseFolding.txt statuses C and F) as [codePoint, ...foldedCodePoints].\n */\n\n")
out.write(f'export const unicodeVersion = "{unicodedata.unidata_version}"\n\n')
out.write("export const forbiddenCodePointRanges: ReadonlyArray<readonly [number, number]> = [\n")
for start, end in ranges:
    out.write(f"  [0x{start:x}, 0x{end:x}],\n")
out.write("]\n\n")
out.write("export const caseFoldings: ReadonlyArray<ReadonlyArray<number>> = [\n")
for entry in folds:
    out.write("  [" + ", ".join(f"0x{value:x}" for value in entry) + "],\n")
out.write("]\n")
