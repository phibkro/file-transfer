import { readdir, readFile, writeFile } from "node:fs/promises"
import path from "node:path"
import { createRequire } from "node:module"

const require = createRequire(import.meta.url)
const packageDirectory = path.dirname(require.resolve("pdfjs-dist/package.json"))
const outputPath = path.resolve(import.meta.dir, "../src/preview/pdfResourceManifest.ts")

const directories = [
  { directory: "cmaps", extensions: [".bcmap"], name: "cMaps" },
  { directory: "standard_fonts", extensions: [".pfb", ".ttf"], name: "standardFonts" },
] as const

const groups = await Promise.all(
  directories.map(async (group) => {
    const files = await readdir(path.resolve(packageDirectory, group.directory))

    return { ...group, files: files.filter((file) => group.extensions.some((extension) => file.endsWith(extension))).toSorted() }
  }),
)

const imports = groups.flatMap((group) =>
  group.files.map((file, index) => `import ${group.name}${index} from "pdfjs-dist/${group.directory}/${file}?url&inline"`),
)

const exports = groups.map(
  (group) =>
    `export const ${group.name} = new Map([\n${group.files.map((file, index) => `  [${JSON.stringify(file)}, ${group.name}${index}],`).join("\n")}\n])`,
)

const generated = `// Generated by apps/web/scripts/generatePdfResources.ts from the pinned pdfjs-dist package.\n${imports.join("\n")}\n\n${exports.join("\n\n")}\n`

if (process.argv.includes("--check")) {
  if ((await readFile(outputPath, "utf-8")) !== generated) {
    process.stderr.write("PDF resource manifest is out of date. Run bun scripts/generatePdfResources.ts from apps/web.\n")
    process.exitCode = 1
  }
} else {
  await writeFile(outputPath, generated)
}
