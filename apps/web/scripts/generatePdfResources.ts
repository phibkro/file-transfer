import { readdir, readFile, writeFile } from "node:fs/promises"
import { createHash } from "node:crypto"
import path from "node:path"
import { createRequire } from "node:module"

const require = createRequire(import.meta.url)
const packageDirectory = path.dirname(require.resolve("pdfjs-dist/package.json"))
const outputPath = path.resolve(import.meta.dir, "../src/preview/pdfResourceManifest.ts")
const noticesPath = path.resolve(import.meta.dir, "../public/pdfjs-notices.txt")

const directories = [
  { directory: "cmaps", extensions: [".bcmap"], name: "cMaps" },
  { directory: "standard_fonts", extensions: [".pfb", ".ttf"], name: "standardFonts" },
] as const

const groups = await Promise.all(
  directories.map(async (group) => {
    const files = await readdir(path.resolve(packageDirectory, group.directory))

    return { ...group, files: files.filter((file) => group.extensions.some((extension) => file.endsWith(extension))).toSorted() }
  }),
)

const imports = groups.flatMap((group) =>
  group.files.map((file, index) => `import ${group.name}${index} from "pdfjs-dist/${group.directory}/${file}?url&inline"`),
)

const exports = groups.map(
  (group) =>
    `export const ${group.name} = new Map([\n${group.files.map((file, index) => `  [${JSON.stringify(file)}, ${group.name}${index}],`).join("\n")}\n])`,
)

const generated = `// Generated by apps/web/scripts/generatePdfResources.ts from the pinned pdfjs-dist package.\n${imports.join("\n")}\n\n${exports.join("\n\n")}\n`

const pdfScript = await readFile(path.resolve(packageDirectory, "build/pdf.mjs"), "utf-8")

if (!pdfScript.includes("pdfjsVersion = 6.5.438")) {
  process.stderr.write("Review PDF.js notices and corresponding font source before upgrading.\n")
  process.exitCode = 1
}

const mark = await readFile(path.resolve(import.meta.dir, "../public/mark.svg"), "utf-8")
const markNotice = /^<!--[\s\S]*?-->/u.exec(mark)?.[0]

if (markNotice === undefined) {
  throw new Error("The Lucide icon notice is missing from mark.svg.")
}

const wasmFiles = await readdir(path.resolve(packageDirectory, "wasm"))
const wasmLicenses = wasmFiles.filter((file) => file.startsWith("LICENSE_")).toSorted()

const wasmNotices = await Promise.all(
  wasmLicenses.map(async (file) => `PDF.js bundled codec: ${file}\n\n${await readFile(path.resolve(packageDirectory, "wasm", file), "utf-8")}`),
)

const notices = [
  "Lucide package icon",
  markNotice,
  "PDF.js 6.5.438: upstream JavaScript notice",
  pdfScript.split("\n").slice(0, 20).join("\n"),
  "PDF.js Apache License 2.0",
  await readFile(path.resolve(packageDirectory, "LICENSE"), "utf-8"),
  "Adobe CMaps",
  await readFile(path.resolve(packageDirectory, "cmaps/LICENSE"), "utf-8"),
  "Foxit standard fonts (PDF.js upstream additionally identifies: Original code copyright 2014 Foxit Software Inc. http://www.foxitsoftware.com)",
  await readFile(path.resolve(packageDirectory, "standard_fonts/LICENSE_FOXIT"), "utf-8"),
  ...wasmNotices,
  "Liberation Sans 1.07.4 standard fonts (corresponding source: liberation-fonts-1.07.4-source.tar.gz, SHA256 ad98b7498dc2992f7f0868f79b65ce4a720a3acdb63ab3f1f1cb6881117a5406; source archive: https://archive.debian.org/debian/pool/main/f/fonts-liberation/fonts-liberation_1.07.4.orig.tar.gz)",
  await readFile(path.resolve(packageDirectory, "standard_fonts/LICENSE_LIBERATION"), "utf-8"),
].join("\n\n")

const sourceArchive = path.resolve(import.meta.dir, "../public/liberation-fonts-1.07.4-source.tar.gz")

const sourceHash = createHash("sha256")
  .update(await readFile(sourceArchive))
  .digest("hex")

if (sourceHash !== "ad98b7498dc2992f7f0868f79b65ce4a720a3acdb63ab3f1f1cb6881117a5406") {
  process.stderr.write("Liberation font source archive checksum mismatch.\n")
  process.exitCode = 1
}

const outputs = [
  { path: outputPath, content: generated },
  { path: noticesPath, content: notices },
]

if (process.argv.includes("--check")) {
  for (const output of outputs) {
    if ((await readFile(output.path, "utf-8")) !== output.content) {
      process.stderr.write("PDF resource output is out of date. Run bun scripts/generatePdfResources.ts from apps/web.\n")
      process.exitCode = 1
    }
  }
} else {
  for (const output of outputs) {
    await writeFile(output.path, output.content)
  }
}
