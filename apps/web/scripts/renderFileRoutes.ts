import type { FileRoute } from "./fileRoutes.ts"

const routerName = (route: FileRoute) => `${route.tag.charAt(0).toLowerCase()}${route.tag.slice(1)}Router`
const parameters = (route: FileRoute) => route.segments.filter((segment) => segment.startsWith("$")).map((segment) => segment.slice(1))

export const renderFileRoutes = (routes: readonly FileRoute[]): string => {
  const pages = routes.filter((route) => !route.layout)
  const name = (route: FileRoute) => `route${routes.indexOf(route)}`

  const schema = (route: FileRoute) =>
    parameters(route)
      .map((parameter) => `${parameter}: ${name(route)}.options.params.${parameter}`)
      .join(", ")

  const parser = (route: FileRoute) => {
    const pieces = route.segments.map((segment) =>
      segment.startsWith("$")
        ? `Route.schemaSegment(${JSON.stringify(segment.slice(1))}, ${name(route)}.options.params.${segment.slice(1)})`
        : `Route.literal(${JSON.stringify(segment)})`,
    )

    return `pipe(${pieces.length ? pieces[0] : "Route.root"}${pieces
      .slice(1)
      .map((piece) => `, Route.slash(${piece})`)
      .join("")}, Route.mapTo(AppRoute.${route.tag}))`
  }

  const specificity = pages.toSorted((left, right) => {
    for (let index = 0; index < Math.min(left.segments.length, right.segments.length); index++) {
      const difference = Number(left.segments[index]?.startsWith("$")) - Number(right.segments[index]?.startsWith("$"))

      if (difference !== 0) {
        return difference
      }
    }

    return right.segments.length - left.segments.length || left.path.localeCompare(right.path, "en")
  })

  const segments = (route: FileRoute) =>
    `[${route.segments.map((segment) => (segment.startsWith("$") ? `{ name: ${JSON.stringify(segment.slice(1))}, schema: ${name(route)}.options.params.${segment.slice(1)} }` : JSON.stringify(segment))).join(", ")}]`

  const imports = routes.map((route, index) => `import { Route as route${index} } from "../routes/${route.file}"`).join("\n")

  const builders = pages
    .map((route) => {
      const params = parameters(route)

      const printer = params.length
        ? `(params) => ${params.map((parameter) => `params.${parameter} === undefined`).join(" || ")} ? undefined : ${routerName(route)}({ ${params.map((parameter) => `${parameter}: params.${parameter}`).join(", ")} })`
        : `() => ${routerName(route)}()`

      return `  ${JSON.stringify(route.path)}: ${printer},`
    })
    .join("\n")

  const routeParameters = pages
    .map((route) => {
      const params = parameters(route)

      return `  ${JSON.stringify(route.path)}: ${params.length ? `{ ${params.map((parameter) => `readonly ${parameter}: string`).join("; ")} }` : "never"}`
    })
    .join("\n")

  return `// Generated by scripts/fileRoutes.ts. Do not edit.
import { pipe } from "effect"
import * as Route from "foldkit/route"
import { buildRoutePath, parsePathname } from "./pathname.ts"
import { Route as rootRoute } from "../routes/__root.ts"
${imports}

export type FileRouteId = ${routes.map((route) => JSON.stringify(route.id)).join(" | ") || "never"}

export const AppRoute = Route.defineRouteUnion({
${pages.map((route) => `  ${route.tag}: { ${schema(route)} },`).join("\n")}
})

export const MainRoute = AppRoute.subset([${pages.flatMap((route) => (route.main ? [JSON.stringify(route.tag)] : [])).join(", ")}])

${pages.map((route) => `export const ${routerName(route)} = ${parser(route)}`).join("\n\n")}

export const router = Route.oneOf(${specificity.map(routerName).join(", ")})

export const routeTree = { root: rootRoute, routes: [
${routes.map((route) => `  { route: ${name(route)}, id: ${JSON.stringify(route.id)}, parent: ${JSON.stringify(route.parent)}, path: ${JSON.stringify(route.path)}, layout: ${route.layout} },`).join("\n")}
] } as const

const paths = {
${pages.map((route) => `  ${JSON.stringify(route.path)}: ${segments(route)},`).join("\n")}
} as const

const builders = {
${builders}
} satisfies { readonly [Path in keyof typeof paths]: (params: Readonly<Record<string, string>>) => string | undefined }

export type RoutePath = keyof typeof paths

interface RouteParameters {
${routeParameters}
}

export const buildPath = <Path extends RoutePath, Params extends RouteParameters[NoInfer<Path>]>(path: Path, ...args: [RouteParameters[NoInfer<Path>]] extends [never] ? [] : [params: Params & Record<Exclude<keyof Params, keyof RouteParameters[NoInfer<Path>]>, never>]): string | undefined => buildRoutePath(paths[path], args[0], builders[path])

export const parsePath = (pathname: string) => parsePathname(pathname, router)
`
}
